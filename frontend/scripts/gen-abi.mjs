// Copies ABIs from forge artifacts (../out) into typed TS modules. Run `forge build` first.
import { readFileSync, writeFileSync } from "node:fs";

const contracts = ["StreamSubscription", "StreamSubscriptionFactory"];
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(new URL(`../../out/${name}.sol/${name}.json`, import.meta.url)));
  const out = `// generated by scripts/gen-abi.mjs, do not edit\nexport const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(new URL(`../src/abi/${name}.ts`, import.meta.url), out);
  console.log(`src/abi/${name}.ts`);
}
